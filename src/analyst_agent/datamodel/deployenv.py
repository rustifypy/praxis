"""The environment file the deployment is run with, rendered from the row.

**This is the whole hand-over.** The portal does not run Cube: it holds the credentials and the
secrets, renders them as an `.env`, and whoever runs `docker compose up` in `semantic/` pastes
back the address. So this file is the one place that decides what a deployment needs, and
`semantic/docker-compose.yml` is the one place that decides what it does with it — the compose
file is served verbatim and never generated, because a generated one is a second copy of the
deployment that can drift from the tested one.

Rendered on demand rather than once at connect time, so reloading the page shows the same file
and rotating a secret is a re-render.
"""

from ..core.deployment import Deployment
from .drivers import credentials_for, get

MOUNT_NOTE = "# A key file: this path has to exist on the machine running the deployment."


def render(deployment: Deployment) -> str:
    """The `.env` for `semantic/docker-compose.yml`, as a person reads and edits it.

    Production mode by default: it is the correct setting the moment this runs anywhere but a
    laptop, and Cube Store is a real container rather than one embedded in the Cube process. Dev
    mode is a commented line rather than a choice in the form — it turns JWT verification off,
    which is a decision to make while looking at the file. It is also no longer dangerous from
    outside: Cube has no published port, so the only door is the store's token either way.
    """
    spec = get(deployment.driver)
    lines = [
        "# Generated by analyst. Save this as `.env` beside semantic/docker-compose.yml, then:",
        "#     docker compose up -d",
        "# Then paste the two addresses back into the portal.",
        "",
        "# --- the warehouse Cube queries ---",
    ]
    lines += [
        f"{key}={value}" for key, value in credentials_for(spec, deployment.credentials).items()
    ]

    lines += [
        "",
        "# --- secrets the portal minted ---",
        "# Shared by cube and model-store and internal to this file: the store signs Cube's",
        "# tokens, so nothing outside the deployment ever holds this.",
        f"CUBEJS_API_SECRET={deployment.api_secret}",
        f"MODEL_STORE_READ_TOKEN={deployment.store_read_token}",
        f"MODEL_STORE_WRITE_TOKEN={deployment.store_token}",
        "",
        "# --- where it listens ---",
        "# One port. Cube is not published — queries reach it through the store at /cube/...,",
        "# which is what makes that the only authenticated door in.",
        "MODEL_STORE_PORT=8500",
        "CUBEJS_DEV_MODE=false",
        "# Dev mode embeds Cube Store, so `cubestore` becomes unnecessary — and disables JWT",
        "# verification entirely. Only correct while nothing outside that host can reach it.",
        "",
        "# `latest` is amd64 only, so an Apple Silicon host needs this.",
        "# CUBESTORE_TAG=arm64v8",
    ]

    # A driver needing its own Cube build says so here rather than the person discovering it
    # from a driver-not-found at query time.
    if spec.tag:
        lines += ["", f"# {spec.label} needs this build of Cube.", f"CUBE_TAG={spec.tag}"]
    if spec.platform:
        lines += [f"CUBE_PLATFORM={spec.platform}"]

    if deployment.mounts:
        # The compose file mounts nothing extra, so a key file is the one thing this cannot
        # hand over — naming both paths is the most it can honestly do.
        lines += ["", MOUNT_NOTE]
        lines += [
            f"#   {host_path}  ->  {container_path}"
            for container_path, host_path in sorted(deployment.mounts.items())
        ]
    return "\n".join(lines) + "\n"


def render_sandbox(deployment: Deployment) -> str:
    """The `.env` for `sandbox-service/docker-compose.yml`.

    Its own file because it is its own deployment: the sandbox shares no network, volume or
    secret with the semantic layer, and one file holding both would suggest they have to run
    together. They do not — and a machine with no sandbox is a working install that just cannot
    run Python.
    """
    return (
        "\n".join(
            [
                "# Generated by analyst. Save this as `.env` beside",
                "# sandbox-service/docker-compose.yml, then:",
                "#     docker compose up -d",
                "# Then paste its address into the portal.",
                "",
                "# It runs arbitrary Python, so this is required rather than optional.",
                f"SANDBOX_TOKEN={deployment.sandbox_token}",
                "SANDBOX_PORT=8600",
            ]
        )
        + "\n"
    )

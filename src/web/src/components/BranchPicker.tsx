import { useState } from "react";

import { useDismiss } from "../hooks";
import type { Refs } from "../sources";
import { Badge } from "./Badge";
import { Button } from "./Button";

const BIN = (
  <svg
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    strokeWidth="1.6"
    strokeLinecap="round"
    strokeLinejoin="round"
  >
    <path d="M4 7h16" />
    <path d="M9.5 7V4.8h5V7" />
    <path d="M6.2 7l.8 12.2a1.6 1.6 0 0 0 1.6 1.5h6.8a1.6 1.6 0 0 0 1.6-1.5L17.8 7" />
    <path d="M10.3 11v6M13.7 11v6" />
  </svg>
);

/**
 * Which branch of the model you are on, and its state. Delete is per row, since the branch worth
 * dropping is usually one you are not on. Main is never offered (the server refuses it too).
 */
export function BranchPicker({
  refs,
  on,
  main,
  busy,
  onSwitch,
  onCreate,
  onDelete,
}: {
  refs: Refs | null;
  on: string;
  /** The generated branch, which is never editable. */
  main: string;
  busy: boolean;
  onSwitch: (ref: string) => void;
  onCreate: () => void;
  /** The parent confirms and makes the call. */
  onDelete: (ref: string) => void;
}) {
  const [open, setOpen] = useState(false);
  const ref = useDismiss<HTMLDivElement>(open, () => setOpen(false));
  const current = refs?.refs.find((r) => r.name === on);

  return (
    <div className="branch" ref={ref}>
      <Button
        className="branch-button"
        aria-haspopup="menu"
        aria-expanded={open}
        disabled={busy}
        title="Which branch of the model you are looking at"
        onClick={() => setOpen(!open)}
      >
        <span className="branch-glyph" aria-hidden>
          ⑂
        </span>
        <span className="branch-name">{on}</span>
        {on === main ? (
          <Badge variant="chip">read-only</Badge>
        ) : current?.changed ? (
          <Badge variant="chip" tone="accent">{current.changed} changed</Badge>
        ) : null}
        <span className="branch-caret" aria-hidden>
          ▾
        </span>
      </Button>

      {open && (
        <div className="branch-panel" role="menu">
          {refs?.refs.map((r) => (
            /* A row, not one button: it holds two buttons, and buttons can't nest. */
            <div className="branch-row" key={r.name}>
              <Button
                role="menuitem"
                className={r.name === on ? "on" : undefined}
                onClick={() => {
                  setOpen(false);
                  if (r.name !== on) onSwitch(r.name);
                }}
              >
                <span className="branch-name">{r.name}</span>
                {r.name === main && <small>generated by the pipeline · read-only</small>}
                {r.changed > 0 && <Badge variant="chip" tone="accent">{r.changed}</Badge>}
              </Button>
              {r.name !== main && (
                <Button
                  icon
                  size="sm"
                  className="branch-delete"
                  aria-label={`Delete branch ${r.name}`}
                  title={`Delete branch ${r.name}`}
                  onClick={() => {
                    setOpen(false);
                    onDelete(r.name);
                  }}
                >
                  {BIN}
                </Button>
              )}
            </div>
          ))}
          <div className="branch-sep" />
          <Button
            role="menuitem"
            onClick={() => {
              setOpen(false);
              onCreate();
            }}
          >
            <span className="branch-name">New branch…</span>
          </Button>
        </div>
      )}
    </div>
  );
}

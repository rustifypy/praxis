import { useState } from "react";

import { useDismiss } from "../hooks";
import type { Refs } from "../sources";
import { Badge } from "./Badge";
import { Button } from "./Button";

/**
 * Which branch of the model you are on, and what it would cost to leave it.
 *
 * A native `<select>` was doing this, and it could say exactly one thing: a name. Everything that
 * decides whether you *should* be here — that main is generated and refuses edits, that another
 * branch has eight uncommitted files — either went unsaid or was crammed into the option label.
 * A read-only branch that looks identical to a writable one is a question you answer by clicking
 * a file and reading the empty state.
 *
 * So the trigger carries the state and not just the name, and creating a branch is an item in the
 * list rather than a button beside it — "start a new one" belongs with "switch to one".
 */
export function BranchPicker({
  refs,
  on,
  main,
  busy,
  onSwitch,
  onCreate,
}: {
  refs: Refs | null;
  /** The branch being shown. */
  on: string;
  /** The generated branch, which is never editable. */
  main: string;
  busy: boolean;
  onSwitch: (ref: string) => void;
  onCreate: () => void;
}) {
  const [open, setOpen] = useState(false);
  const ref = useDismiss<HTMLDivElement>(open, () => setOpen(false));
  const current = refs?.refs.find((r) => r.name === on);

  return (
    <div className="branch" ref={ref}>
      <Button
        className="branch-button"
        aria-haspopup="menu"
        aria-expanded={open}
        disabled={busy}
        title="Which branch of the model you are looking at"
        onClick={() => setOpen(!open)}
      >
        <span className="branch-glyph" aria-hidden>
          ⑂
        </span>
        <span className="branch-name">{on}</span>
        {/* One of the two, never both: on main the count is always zero by construction, and
            "read-only" is the only thing worth the width. */}
        {on === main ? (
          <Badge variant="chip">read-only</Badge>
        ) : current?.changed ? (
          <Badge variant="chip" tone="accent">{current.changed} changed</Badge>
        ) : null}
        <span className="branch-caret" aria-hidden>
          ▾
        </span>
      </Button>

      {open && (
        <div className="branch-panel" role="menu">
          {refs?.refs.map((r) => (
            <Button
              key={r.name}
              role="menuitem"
              className={r.name === on ? "on" : undefined}
              onClick={() => {
                setOpen(false);
                if (r.name !== on) onSwitch(r.name);
              }}
            >
              <span className="branch-name">{r.name}</span>
              {r.name === main && <small>generated by the pipeline · read-only</small>}
              {r.changed > 0 && <Badge variant="chip" tone="accent">{r.changed}</Badge>}
            </Button>
          ))}
          <div className="branch-sep" />
          <Button
            role="menuitem"
            onClick={() => {
              setOpen(false);
              onCreate();
            }}
          >
            <span className="branch-name">New branch…</span>
          </Button>
        </div>
      )}
    </div>
  );
}
